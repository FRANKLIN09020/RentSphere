import { useState } from 'react'
import {
  Alert,
  Box,
  Button,
  Chip,
  CircularProgress,
  Dialog,
  DialogContent,
  DialogTitle,
  Divider,
  Stack,
  Typography,
} from '@mui/material'
import { getErrorMessage, http } from '../../shared/api/http'

type SettlementAdvice = {
  recommendedDeduction: number | string
  suggestedRefund: number | string
  rationale: string
  usedFallback: boolean
  model: string
}

const money = (value: number | string) =>
  `₹${Number(value ?? 0).toLocaleString('en-IN', { maximumFractionDigits: 2 })}`

export function SettlementAdviceButton({ recordId }: { recordId: string }) {
  const [open, setOpen] = useState(false)
  const [loading, setLoading] = useState(false)
  const [advice, setAdvice] = useState<SettlementAdvice | null>(null)
  const [error, setError] = useState('')

  async function openAdvice() {
    setOpen(true)
    setLoading(true)
    setError('')
    setAdvice(null)
    try {
      const response = await http.get<SettlementAdvice>(`/deposit-disputes/${recordId}/settlement-advice`)
      setAdvice(response.data)
    } catch (err) {
      setError(getErrorMessage(err))
    } finally {
      setLoading(false)
    }
  }

  return (
    <>
      <Button
        size="small"
        onClick={() => void openAdvice()}
        title="AI settlement advice"
        aria-label="AI settlement advice"
        sx={{ minWidth: 32, width: 32, height: 32, borderRadius: '9px', p: 0, color: 'text.secondary', bgcolor: 'color-mix(in srgb, var(--rs-primary) 8%, transparent)', transition: 'all 0.2s ease', '&:hover': { bgcolor: 'color-mix(in srgb, var(--rs-primary) 16%, transparent)', color: 'primary.main', transform: 'scale(1.1) translateY(-2px)' } }}
      >
        <Box component="span" sx={{ fontSize: 15, fontWeight: 800, lineHeight: 1 }}>AI</Box>
      </Button>
      <Dialog open={open} onClose={() => setOpen(false)} maxWidth="sm" fullWidth>
        <DialogTitle sx={{ fontWeight: 800 }}>AI settlement advice</DialogTitle>
        <DialogContent>
          {loading && (
            <Stack sx={{ py: 4, alignItems: 'center' }}>
              <CircularProgress size={28} />
              <Typography variant="body2" color="text.secondary" sx={{ mt: 1.5 }}>
                Analyzing repair estimates...
              </Typography>
            </Stack>
          )}
          {!loading && error && <Alert severity="error">{error}</Alert>}
          {!loading && advice && (
            <Stack spacing={2}>
              <Stack direction="row" spacing={1} sx={{ alignItems: 'center' }}>
                {advice.usedFallback
                  ? <Chip size="small" label="Rule-based estimate" color="warning" />
                  : <Chip size="small" label={`Llama · ${advice.model}`} color="primary" />}
              </Stack>
              <Stack direction={{ xs: 'column', sm: 'row' }} spacing={2}>
                <Box sx={{ flex: 1, p: 1.5, borderRadius: '12px', bgcolor: 'rgba(185,28,28,0.06)', border: '1px solid', borderColor: 'rgba(185,28,28,0.18)' }}>
                  <Typography variant="caption" color="text.secondary" sx={{ fontWeight: 700 }}>Fair deduction</Typography>
                  <Typography sx={{ fontWeight: 800, fontSize: '1.15rem', color: 'error.main' }}>
                    {money(advice.recommendedDeduction)}
                  </Typography>
                </Box>
                <Box sx={{ flex: 1, p: 1.5, borderRadius: '12px', bgcolor: 'rgba(22,163,74,0.07)', border: '1px solid', borderColor: 'rgba(22,163,74,0.2)' }}>
                  <Typography variant="caption" color="text.secondary" sx={{ fontWeight: 700 }}>Suggested refund</Typography>
                  <Typography sx={{ fontWeight: 800, fontSize: '1.15rem', color: 'success.main' }}>
                    {money(advice.suggestedRefund)}
                  </Typography>
                </Box>
              </Stack>
              <Divider />
              <Typography variant="body2" sx={{ whiteSpace: 'pre-line' }}>{advice.rationale}</Typography>
              {advice.usedFallback && (
                <Alert severity="info" sx={{ mt: 1 }}>
                  Generated by built-in rules. Configure GROQ_API_KEY for full Llama analysis.
                </Alert>
              )}
            </Stack>
          )}
        </DialogContent>
      </Dialog>
    </>
  )
}
